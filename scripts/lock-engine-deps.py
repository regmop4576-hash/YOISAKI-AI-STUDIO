"""Writes cloudcompute/requirements-lock.txt from a `pip install --dry-run --report` of the image requirements.

Reproducible procedure (run on any Docker host, from the package root):
  docker run --rm -v "$PWD:/src:ro" -v "$PWD/build-lock:/out" nvidia/cuda:12.8.1-base-ubuntu24.04 bash -c '
    apt-get update -qq && apt-get install -y -qq python3 python3-venv >/dev/null && python3 -m venv /v &&
    cat /src/cloudcompute/requirements-cloud.txt /src/engine/requirements.txt | grep -v "^#" | grep . > /out/all.txt &&
    /v/bin/pip install --dry-run --ignore-installed --quiet --report /out/report.json -r /out/all.txt'
  python3 scripts/lock-engine-deps.py build-lock/report.json
Every wheel is pinned by version AND sha256 (linux x86_64, CPython 3.12 = Ubuntu 24.04 python3).
"""
import json
import sys
from pathlib import Path

APP = Path(__file__).resolve().parents[1]


def lock_lines(report):
    rows = []
    for item in report['install']:
        meta, info = item['metadata'], item['download_info']
        digest = info.get('archive_info', {}).get('hashes', {}).get('sha256')
        if not digest:
            raise SystemExit(f"{meta['name']}: no sha256 in the pip report")
        rows.append((meta['name'].lower().replace('_', '-'), meta['version'], digest))
    rows.sort()
    return [f'{name}=={version} \\\n    --hash=sha256:{digest}' for name, version, digest in rows]


def main(argv):
    report = json.loads(Path(argv[1]).read_text())
    header = ['# YOISAKI ENGINE CloudCompute image: complete, hash-pinned dependency set (generated by scripts/lock-engine-deps.py).',
              '# Installed with `pip install --require-hashes --no-deps`; top-level pins live in cloudcompute/requirements-cloud.txt',
              '# and engine/requirements.txt (cloudcompute/check_lock.py verifies the lock satisfies both). Do not edit by hand.']
    target = APP / 'cloudcompute/requirements-lock.txt'
    target.write_text('\n'.join(header + lock_lines(report)) + '\n')
    print(f'{target.relative_to(APP)}: {len(report["install"])} packages')


if __name__ == '__main__':
    main(sys.argv)
