// PIXEL FANTASY frame generator (design-time tool).
//   node scripts/pixel-frames.mjs  →  src/app/pixel-frames.css
// Every frame is a tiny SVG grid (1 unit = 1 art pixel) drawn ring by ring with stepped corners, exported as a
// data-URI custom property for `border-image`. The UI stays real DOM: frames only decorate the border box.
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const C={
 K:'#04050b',G:'#f0b03c',H:'#ffe39a',A:'#a8681a',D:'#4a2e0c',Y:'#ffd166',O:'#ff9a1f',R:'#b9520f',S:'#fff0c4',
 P:'#0b1023',Q:'#10172e',B:'#151c38',I:'#060915',N:'#21180c',M:'#8f6420',E:'#ff6a55',e:'#5c1a16',F:'#2a0f10',
 g:'#5fd47a',j:'#1d4a2a',k:'#0d2014',T:'#2a2010',U:'#3a2a10',L:'#1b2347',W:'#6b7bb8',
};
/** rings[k] is a color key or [topLeft,bottomRight] for a bevel; notch = stepped corner depth; rivet adds corner jewels. */
function frame({rings,notch=2,rivet=null}){
 const s=rings.length,n=s*2+1;const grid=[];
 for(let y=0;y<n;y++)for(let x=0;x<n;x++){
  const dx=Math.min(x,n-1-x),dy=Math.min(y,n-1-y);
  if(dx+dy<notch)continue;
  const ring=Math.min(dx,dy,dx+dy-notch);if(ring>=s)continue;
  let key=rings[ring];
  if(Array.isArray(key)){const topLeft=(dy<=dx?y<n/2:x<n/2);key=topLeft?key[0]:key[1]}
  if(rivet&&dx===rivet.at&&dy===rivet.at)key=rivet.key;
  (grid[y]??=[])[x]=C[key];
 }
 // One path per colour built from horizontal runs keeps each frame well under 1 KB.
 const paths={};
 for(let y=0;y<n;y++){let x=0;while(x<n){const c=grid[y]?.[x];if(!c){x++;continue}let w=1;while(grid[y][x+w]===c)w++;paths[c]=(paths[c]||'')+`M${x} ${y}h${w}v1h-${w}z`;x+=w}}
 const svg=`<svg xmlns='http://www.w3.org/2000/svg' width='${n}' height='${n}' viewBox='0 0 ${n} ${n}' shape-rendering='crispEdges'>`+Object.entries(paths).map(([c,d])=>`<path fill='${c}' d='${d}'/>`).join('')+'</svg>';
 return {slice:s,uri:`url("data:image/svg+xml,${svg.replace(/#/g,'%23').replace(/</g,'%3C').replace(/>/g,'%3E')}")`};
}
const frames={
 panel:frame({rings:['G','K','A','P','P'],notch:3,rivet:{at:2,key:'H'}}),
 card:frame({rings:['M','Q','Q'],notch:2}),
 'card-on':frame({rings:['G','T','T'],notch:2}),
 btn:frame({rings:['A',['M','K'],'B'],notch:2}),
 'btn-hover':frame({rings:['G',['H','D'],'B'],notch:2}),
 'btn-down':frame({rings:['G',['K','M'],'B'],notch:2}),
 primary:frame({rings:['Y',['S','R'],'O'],notch:2}),
 'primary-down':frame({rings:['Y',['R','S'],'O'],notch:2}),
 selected:frame({rings:['Y',['S','R'],'O'],notch:2}),
 input:frame({rings:['M',['K','L'],'I'],notch:1}),
 'input-focus':frame({rings:['Y',['K','A'],'I'],notch:1}),
 notice:frame({rings:['A','N','N'],notch:2}),
 danger:frame({rings:['E','F','F'],notch:2}),
 ok:frame({rings:['g','k','k'],notch:2}),
 modal:frame({rings:['K','G','K',['H','D'],'P','P'],notch:4,rivet:{at:3,key:'S'}}),
 hero:frame({rings:['K','Y','K',['S','R'],'O','O'],notch:4,rivet:{at:3,key:'S'}}),
 'hero-down':frame({rings:['K','Y','K',['R','S'],'O','O'],notch:4,rivet:{at:3,key:'S'}}),
 'hero-busy':frame({rings:['K','A','K',['M','D'],'T','T'],notch:4,rivet:{at:3,key:'Y'}}),
 nav:frame({rings:['G',['H','D'],'T','T'],notch:2}),
 chip:frame({rings:['M','Q'],notch:1}),
 'chip-ok':frame({rings:['g','k'],notch:1}),
 'chip-warn':frame({rings:['G','T'],notch:1}),
 'chip-bad':frame({rings:['E','F'],notch:1}),
};
let css='/* GENERATED by scripts/pixel-frames.mjs — do not edit by hand. PIXEL FANTASY border-image frames. */\n:root{\n';
for(const [name,f] of Object.entries(frames))css+=` --fx-${name}:${f.uri};\n --fx-${name}-s:${f.slice};\n`;
css+='}\n';
await fs.writeFile(path.join(root,'src/app/pixel-frames.css'),css);
console.log('pixel frames:',Object.keys(frames).length);
